// Pulls the text of every page on the site into the assistant's knowledge.
// Run from the repo root:  node assistant-worker/build-knowledge.mjs
// Re-run whenever a page is added or changed, then redeploy the Worker.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteDir = join(here, "..");
const out = join(here, "src", "knowledge.mmc.js");

const decode = (s) =>
  s.replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&rarr;/g, "→")
   .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'");

function pageText(html) {
  const title = (html.match(/<title>([\s\S]*?)<\/title>/i) || [, ""])[1].trim();
  let body = html
    .replace(/<head>[\s\S]*?<\/head>/i, "")
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<style[\s\S]*?<\/style>/gi, "")
    .replace(/<header>[\s\S]*?<\/header>/i, "")
    .replace(/<footer>[\s\S]*?<\/footer>/i, "")
    .replace(/<form[\s\S]*?<\/form>/gi, "")
    .replace(/<aside class="side-card">[\s\S]*?<\/aside>/gi, "");
  body = body
    .replace(/<\/(h[1-6])>/gi, "\n")
    .replace(/<(h[1-6])[^>]*>/gi, "\n## ")
    .replace(/<li[^>]*>/gi, "\n- ")
    .replace(/<summary[^>]*>/gi, "\nQ: ")
    .replace(/<\/summary>\s*<p>/gi, "\nA: ")
    .replace(/<\/(p|div|section|details|ul|li)>/gi, "\n")
    .replace(/<[^>]+>/g, " ");
  body = decode(body).split("\n").map((l) => l.replace(/\s+/g, " ").trim()).filter(Boolean).join("\n");
  return { title, body };
}

const files = readdirSync(siteDir).filter((f) => f.endsWith(".html")).sort((a, b) =>
  a === "index.html" ? -1 : b === "index.html" ? 1 : a.localeCompare(b));

const parts = files.map((f) => {
  const { title, body } = pageText(readFileSync(join(siteDir, f), "utf8"));
  return `=== PAGE: /${f} — ${title} ===\n${body}`;
});

const text = parts.join("\n\n");
writeFileSync(out,
  "// AUTO-GENERATED by build-knowledge.mjs — do not edit by hand.\n" +
  `// ${files.length} pages, ${text.length} characters.\n` +
  `export const MMC_PAGES = ${JSON.stringify(text)};\n`);
console.log(`knowledge: ${files.length} pages, ${text.length} chars -> ${out}`);
